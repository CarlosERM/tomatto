"""P4 — Test-data driven tests.

The dataset in data/blocklist_dataset.json was generated by the LLM output of
prompts/p4-test-data.md (realistic tricky blocklists) and curated here into a
parametrized suite: every accepted input must normalize exactly as predicted,
every rejected input must be refused with 422.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

pytestmark = pytest.mark.integration

DATASET = json.loads((Path(__file__).parent / "data" / "blocklist_dataset.json").read_text())


@pytest.mark.parametrize(
    "case", DATASET["accept"], ids=[c["note"].split(":")[0][:40] for c in DATASET["accept"]]
)
async def test_valid_domains_are_accepted_and_normalized(manager, case):
    resp = await manager.post("/rules", json={"domain": case["input"]})
    assert resp.status_code == 201, f"{case['input']!r} rejected: {resp.text}"
    assert resp.json()["domain"] == case["normalized"]


@pytest.mark.parametrize(
    "case", DATASET["reject"], ids=[c["note"].split(":")[0][:40] for c in DATASET["reject"]]
)
async def test_invalid_domains_are_refused(manager, case):
    resp = await manager.post("/rules", json={"domain": case["input"]})
    assert resp.status_code == 422, f"{case['input']!r} was wrongly accepted"


async def test_whole_accepted_dataset_propagates_to_sync(manager, sync):
    expected = {c["normalized"] for c in DATASET["accept"]}

    for case in DATASET["accept"]:
        resp = await manager.post("/rules", json={"domain": case["input"]})
        # Normalization equivalence: 'example.com', 'example.com.' and
        # 'example.com:8080' are the same rule, so a duplicate after the first
        # normalized form is a legitimate 409, not a failure.
        assert resp.status_code in (201, 409), f"{case['input']!r}: {resp.text}"

    blocked = (await sync.get("/blocked")).json()
    assert {s["domain"] for s in blocked["sites"]} == expected
