"""Merge the OpenAPI specs of both services into docs/openapi.yaml.

The merged spec is the input for prompt P1 (contract tests) — regenerate it
whenever an endpoint or model changes:

    uv run python scripts/export_openapi.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from services.manager_api.main import manager_app  # noqa: E402
from services.sync_api.main import sync_app  # noqa: E402


def main() -> None:
    manager_spec = manager_app.openapi()
    sync_spec = sync_app.openapi()

    merged = {
        "openapi": "3.1.0",
        "info": {
            "title": "Tomatto — combined API contract (Manager + Sync)",
            "version": "1.0.0",
            "description": (
                "Two independent REST services. The Manager API owns the block list and pushes "
                "full-list snapshots (with a monotonic version) to the Sync API's /internal/sync. "
                "The Sync API serves GET /blocked to browser extensions with weak-ETag/304 polling."
            ),
        },
        "paths": {**manager_spec["paths"], **sync_spec["paths"]},
    }
    schemas = {**manager_spec.get("components", {}).get("schemas", {}),
               **sync_spec.get("components", {}).get("schemas", {})}
    if schemas:
        merged["components"] = {"schemas": schemas}

    header = "# Generated by scripts/export_openapi.py — do not edit by hand.\n"
    out = ROOT / "docs" / "openapi.yaml"
    out.write_text(header + yaml.safe_dump(merged, sort_keys=False, allow_unicode=True))
    print(f"wrote {out} ({len(merged['paths'])} paths)")


if __name__ == "__main__":
    main()
